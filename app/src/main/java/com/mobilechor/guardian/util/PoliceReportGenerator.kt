object PoliceReportGenerator {

    fun generateReportHtml(context: Context): String {
        val repo = MobileChorApp.instance.repository
        val state = repo.deviceState.value
        val profile = repo.ownerProfile.value
        val evidenceList = repo.evidenceRepository.evidenceList.value
        val dateStr = SimpleDateFormat("dd MMMM yyyy, hh:mm a", Locale.US).format(Date())

        val photosHtml = StringBuilder()
        if (evidenceList.isEmpty()) {
            photosHtml.append("<p><em>No intruder tamper attempts logged yet.</em></p>")
        } else {
            for (item in evidenceList.take(6)) {
                val time = SecurityUtils.formatTimestamp(item.timestamp)
                photosHtml.append("""
                    <div style="border: 1px solid #ddd; padding: 10px; margin-bottom: 12px; border-radius: 6px; background: #fafafa;">
                        <strong>Trigger:</strong> ${item.triggerReason}<br/>
                        <strong>Timestamp:</strong> $time<br/>
                        <strong>GPS Coordinates:</strong> ${item.latitude}, ${item.longitude}<br/>
                        <strong>Battery:</strong> ${item.batteryAtCapture}% | <strong>Network:</strong> ${item.networkState}<br/>
                        ${if (item.photoPath.isNotEmpty()) "<div style='margin-top:6px; color:#555;'>[Photo Record Attached in Evidence Vault: ${File(item.photoPath).name}]</div>" else ""}
                    </div>
                """.trimIndent())
            }
        }

        return """
        <!DOCTYPE html>
        <html lang="en">
        <head>
            <meta charset="UTF-8">
            <title>Mobile Chor - Official Police Theft Report</title>
            <style>
                body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Arial, sans-serif; padding: 30px; color: #222; background: #fff; line-height: 1.6; }
                .header { border-bottom: 3px solid #0052cc; padding-bottom: 15px; margin-bottom: 25px; }
                .title { font-size: 24px; font-weight: bold; color: #0052cc; margin: 0; }
                .subtitle { font-size: 14px; color: #666; margin-top: 4px; }
                .badge { background: #d73a49; color: white; padding: 4px 8px; border-radius: 4px; font-weight: bold; font-size: 12px; }
                .section { margin-bottom: 25px; }
                .section-title { font-size: 18px; font-weight: bold; border-bottom: 1px solid #eee; padding-bottom: 6px; margin-bottom: 12px; color: #333; }
                table { width: 100%; border-collapse: collapse; margin-top: 8px; }
                th, td { text-align: left; padding: 8px 12px; border: 1px solid #e1e4e8; font-size: 14px; }
                th { background: #f6f8fa; width: 35%; }
                .footer { font-size: 12px; color: #777; border-top: 1px solid #eee; padding-top: 15px; margin-top: 30px; }
                .btrc-box { background: #eef5fc; border-left: 4px solid #0052cc; padding: 12px; margin-top: 15px; font-size: 13px; }
                @media print {
                    body { padding: 10px; }
                    .no-print { display: none; }
                }
            </style>
        </head>
        <body>
            <div class="header">
                <span class="badge">POLICE DOSSIER / GD ATTACHMENT</span>
                <h1 class="title">EMERGENCY THEFT COMPLAINT &amp; DEVICE RECOVERY REPORT</h1>
                <div class="subtitle">Generated by Mobile Chor Anti-Theft Security System on $dateStr</div>
            </div>

            <div class="section">
                <div class="section-title">1. Complainant &amp; Registered Owner Information</div>
                <table>
                    <tr><th>Registered Owner Name</th><td><strong>${profile.ownerName.ifEmpty { "Registered User" }}</strong></td></tr>
                    <tr><th>Primary Contact Number</th><td>${profile.ownerPhone.ifEmpty { "Not specified" }}</td></tr>
                    <tr><th>Primary Email</th><td>${profile.ownerEmail.ifEmpty { "Not specified" }}</td></tr>
                    <tr><th>Emergency Backup Contact</th><td>${profile.emergencyContactName.ifEmpty { "Guardian Contact" }} (${profile.emergencyPhone})</td></tr>
                </table>
            </div>

            <div class="section">
                <div class="section-title">2. Stolen / Lost Device Specifications</div>
                <table>
                    <tr><th>Device Model &amp; Make</th><td><strong>${state.manufacturer} ${state.model}</strong></td></tr>
                    <tr><th>Android OS Version</th><td>${state.androidVersion}</td></tr>
                    <tr><th>Device Hardware ID (Android ID)</th><td><code>${state.deviceId}</code></td></tr>
                    <tr><th>SIM Operator State</th><td>${state.simOperator}</td></tr>
                    <tr><th>Factory Reset Protection (FRP)</th><td>Active (Bound to Google Account: ${profile.ownerEmail.ifEmpty { "Owner Account" }})</td></tr>
                </table>
            </div>

            <div class="section">
                <div class="section-title">3. Last Known Location &amp; Connectivity Telemetry</div>
                <table>
                    <tr><th>GPS Coordinates</th><td><strong>${state.latitude}, ${state.longitude}</strong> (Accuracy: &plusmn;${state.locationAccuracy}m)</td></tr>
                    <tr><th>Live Map Reference</th><td><a href="https://maps.google.com/?q=${state.latitude},${state.longitude}" target="_blank">Open Exact Location on Google Maps</a></td></tr>
                    <tr><th>Network &amp; Access Point</th><td>${state.networkType} (SSID: ${state.wifiSsid})</td></tr>
