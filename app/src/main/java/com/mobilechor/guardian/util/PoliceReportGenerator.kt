        </body>
        </html>
        """.trimIndent()
    }

    fun exportReportToFile(context: Context): File {
        val htmlContent = generateReportHtml(context)
        val reportsDir = File(context.filesDir, "police_reports")
        if (!reportsDir.exists()) {
            reportsDir.mkdirs()
        }
        val file = File(reportsDir, "police_theft_report_${System.currentTimeMillis()}.html")
        FileOutputStream(file).use { fos ->
            fos.write(htmlContent.toByteArray(Charsets.UTF_8))
        }
        return file
    }
}
